SETS = {
    "v1": (OUT, (("partial", make_partial), ("broken", make_broken),
                 ("vague_padded", make_vague), ("swapped", make_swapped))),
    "v2": (OUT_V2, (("partial", make_partial_v2), ("broken", make_broken_v2),
                    ("vague_padded", make_vague_v2), ("swapped", make_swapped_v2))),
    "v3": (OUT_V3, (("partial", make_partial_v3), ("broken", make_broken_v3),
                    ("vague_padded", make_vague_v3), ("swapped", make_swapped_v3))),
}


def main(argv=None) -> None:
    import argparse
    ap = argparse.ArgumentParser(); ap.add_argument("--set", choices=list(SETS), default="v1")
    a = ap.parse_args(argv)
    strong = json.loads(STRONG.read_text(encoding="utf-8"))
    out, makers = SETS[a.set]
    out.mkdir(parents=True, exist_ok=True)
    for name, fn in makers:
        (out / f"fleettrack_{name}.json").write_text(json.dumps(fn(strong), indent=2), encoding="utf-8")
        print("wrote", out / f"fleettrack_{name}.json")


if __name__ == "__main__":
    main()

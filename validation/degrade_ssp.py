"""
Generate the degraded FleetTrack variants for the discriminant test, deterministically
from the strong SSP. Every change is rule-based so it can be audited and regenerated.

    python validation/degrade_ssp.py              # v1 set
    python validation/degrade_ssp.py --set v2     # v2 or v3 set

Variants (rationale and predictions in validation/DISCRIMINANT_PROTOCOL.md):
  partial          aligned      delete every 3rd statement; kept text -> first sentence, artefacts generalised
  broken           aligned      keep only every 3rd statement; text -> one generic line; set-params dropped
  vague_padded     independent  same statements; text -> generic padding of >= original length + 2 decoy file names
  swapped          independent  same statements; descriptions rotated so each lands on a different control
Statement remarks (e.g. "KNOWN GAP") are kept wherever the statement is kept, so the gap cap applies equally.
Controls are never removed (only statements), so Stage 3 pairing is identical across variants.
"""

from __future__ import annotations

import copy
import json
import re
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STRONG = ROOT / "data" / "raw" / "ssps" / "fleettrack" / "fleettrack_ssp.json"
OUT = ROOT / "data" / "raw" / "ssps" / "fleettrack_variants"
NS = uuid.UUID("6f1c2a52-6a8e-4c43-9a43-2f1f6b1d0e10")  # fixed namespace -> stable variant uuids

# Generalising replacements, applied in this order. They target the same artefact
# families the Maturity scorer counts, so partial and broken are feature-aligned by design.
GENERALISE = [
    (re.compile(r"\b[\w./-]+\.(?:py|db|json|ya?ml|conf|md|log|sql|txt|toml|ini|env)\b", re.I), "a configuration file"),
    (re.compile(r"\b(?:AES|TLS|SHA-?\d*|bcrypt|RSA|HMAC|JWT|OAuth2?|SSH|HTTPS|PBKDF2|argon2)\b", re.I), "a standard mechanism"),
    (re.compile(r"\b\d+(?:\.\d+)+\b"), "a supported version"),
    (re.compile(r"\b\d+\s*(?:seconds?|minutes?|hours?|days?|weeks?|months?|years?)\b", re.I), "a defined period"),
    (re.compile(r"\b[A-Za-z]+_[A-Za-z0-9_]+\b(?:\(\))?"), "a named function"),
    (re.compile(r"\b(?:GET|POST|PUT|PATCH|DELETE)\s+/[\w/{}.-]*"), "an endpoint"),
]
VAGUE = [
    "This requirement is addressed through the organization's established approach.",
    "Appropriate measures are applied in line with internal policies and procedures.",
    "Responsibilities are assigned and the approach is reviewed as part of normal operations.",
    "The relevant expectations are communicated to the people involved.",
]
DECOY = "Supporting documentation is kept in policy.md and config.yaml."
BROKEN_LINE = "The system addresses this requirement."


def first_sentence(text: str) -> str:
    m = re.match(r"(.+?[.!?])(\s|$)", text.strip())
    return m.group(1) if m else text.strip()


def generalise(text: str) -> str:
    for rx, rep in GENERALISE:
        text = rx.sub(rep, text)
    return text


def vague_padding(target_words: int) -> str:
    out, i = [DECOY], 0
    while len(" ".join(out).split()) < target_words:
        out.insert(-1, VAGUE[i % len(VAGUE)]); i += 1
    return " ".join(out)


def _statements(ssp: dict):
    """(control-id, statement-id, statement dict) in a fixed, sorted order."""
    rows = []
    for ir in ssp["control-implementation"]["implemented-requirements"]:
        for st in ir.get("statements", []):
            rows.append((ir["control-id"], st["statement-id"], ir, st))
    return sorted(rows, key=lambda r: (r[0], r[1]))


def _retitle(doc: dict, name: str, note: str) -> dict:
    ssp = doc["system-security-plan"]
    ssp["uuid"] = str(uuid.uuid5(NS, name))
    md = ssp["metadata"]
    md["title"] = f"{md.get('title', 'FleetTrack SSP')} [DEGRADED VARIANT: {name}]"
    md.setdefault("remarks", "")
    md["remarks"] = (md["remarks"] + "\n" if md["remarks"] else "") + \
        f"Generated by validation/degrade_ssp.py from the strong FleetTrack SSP. {note}"
    return doc


def make_partial(strong: dict) -> dict:
    doc = copy.deepcopy(strong); ssp = doc["system-security-plan"]
    for i, (_, _, ir, st) in enumerate(_statements(ssp)):
        if i % 3 == 2:
            ir["statements"] = [s for s in ir["statements"] if s is not st]
            continue
        for bc in st.get("by-components", []):
            bc["description"] = generalise(first_sentence(bc["description"]))
    return _retitle(doc, "partial", "Every 3rd statement deleted; kept descriptions cut to the first sentence with artefacts generalised.")


def make_broken(strong: dict) -> dict:
    doc = copy.deepcopy(strong); ssp = doc["system-security-plan"]
    for i, (_, _, ir, st) in enumerate(_statements(ssp)):
        if i % 3 != 0:
            ir["statements"] = [s for s in ir["statements"] if s is not st]
            continue
        for bc in st.get("by-components", []):
            bc["description"] = BROKEN_LINE
            bc.pop("set-parameters", None)
    for ir in ssp["control-implementation"]["implemented-requirements"]:
        ir.pop("set-parameters", None)
    return _retitle(doc, "broken", "Only every 3rd statement kept, each reduced to one generic line; set-parameters removed.")


def make_vague(strong: dict) -> dict:
    doc = copy.deepcopy(strong); ssp = doc["system-security-plan"]
    for _, _, _, st in _statements(ssp):
        for bc in st.get("by-components", []):
            bc["description"] = vague_padding(len(bc["description"].split()))
    return _retitle(doc, "vague_padded", "Same statements; each description replaced by generic padding of at least the original length plus two decoy file names.")


GAP_MARKERS = ("not implemented", "known gap")  # the SSP's own gap declarations


def make_swapped(strong: dict) -> dict:
    """Rotate real implementation texts so each lands on a different control.

    Texts that declare a gap stay in place: moving them would trigger the gap cap on
    other controls and mix two effects. This variant tests wrong-mechanism text only.
    """
    doc = copy.deepcopy(strong); ssp = doc["system-security-plan"]
    slots = [(cid, bc) for cid, _, _, st in _statements(ssp) for bc in st.get("by-components", [])
             if not any(m in bc["description"].lower() for m in GAP_MARKERS)]
    texts = [bc["description"] for _, bc in slots]
    n = len(slots)
    for k in range(1, n):  # smallest rotation that moves every text to a different control
        if all(slots[i][0] != slots[(i - k) % n][0] for i in range(n)):
            break
    else:
        raise RuntimeError("no rotation moves every description to a different control")
    for i, (_, bc) in enumerate(slots):
        bc["description"] = texts[(i - k) % n]
    return _retitle(doc, "swapped", f"Same statements; {n} real implementation descriptions rotated by {k} so each "
                    "describes a different control; declared-gap descriptions left in place.")


# ---------------- v2 rule set (iteration 2; written before any v2 scoring) ----------------
OUT_V2 = ROOT / "data" / "raw" / "ssps" / "fleettrack_variants_v2"
VAGUE_V2 = [
    "The team follows an agreed process for this area.",
    "Controls are maintained and kept under periodic review by the responsible owner.",
    "Any issues are handled through the usual internal channels.",
    "Staff are made aware of what is expected of them.",
]
DECOY_V2 = "Details are recorded in procedures.md and settings.json."
BROKEN_LINE_V2 = "Controls are in place for this area."


def _sentences(text: str) -> list[str]:
    return [x for x in re.split(r"(?<=[.!?])\s+", text.strip()) if x]


def make_partial_v2(strong: dict) -> dict:
    doc = copy.deepcopy(strong); ssp = doc["system-security-plan"]
    for i, (_, _, ir, st) in enumerate(_statements(ssp)):
        if i % 3 == 1:
            ir["statements"] = [s for s in ir["statements"] if s is not st]
            continue
        for bc in st.get("by-components", []):
            sents = _sentences(bc["description"])
            bc["description"] = generalise(" ".join(sents[: max(1, (len(sents) + 1) // 2)]))
    return _retitle(doc, "partial_v2", "v2: statements with index%3==1 deleted; kept text cut to its first half of sentences, artefacts generalised.")


def make_broken_v2(strong: dict) -> dict:
    doc = copy.deepcopy(strong); ssp = doc["system-security-plan"]
    for i, (_, _, ir, st) in enumerate(_statements(ssp)):
        if i % 3 != 1:
            ir["statements"] = [s for s in ir["statements"] if s is not st]
            continue
        for bc in st.get("by-components", []):
            bc["description"] = BROKEN_LINE_V2
            bc.pop("set-parameters", None)
    for ir in ssp["control-implementation"]["implemented-requirements"]:
        ir.pop("set-parameters", None)
    return _retitle(doc, "broken_v2", "v2: only index%3==1 statements kept, each one generic line; set-parameters removed.")


def make_vague_v2(strong: dict) -> dict:
    doc = copy.deepcopy(strong); ssp = doc["system-security-plan"]
    for _, _, _, st in _statements(ssp):
        for bc in st.get("by-components", []):
            target, out, i = len(bc["description"].split()), [DECOY_V2], 0
            while len(" ".join(out).split()) < target:
                out.insert(-1, VAGUE_V2[i % len(VAGUE_V2)]); i += 1
            bc["description"] = " ".join(out)
    return _retitle(doc, "vague_padded_v2", "v2: generic padding (different wording) >= original length plus two different decoy file names.")


def make_swapped_v2(strong: dict) -> dict:
    doc = copy.deepcopy(strong); ssp = doc["system-security-plan"]
    slots = [(cid, bc) for cid, _, _, st in _statements(ssp) for bc in st.get("by-components", [])
             if not any(m in bc["description"].lower() for m in GAP_MARKERS)]
    texts = [bc["description"] for _, bc in slots]; n = len(slots)
    valid = [k for k in range(1, n) if all(slots[i][0] != slots[(i - k) % n][0] for i in range(n))]
    k = valid[1]  # second valid rotation (v1 used the first)
    for i, (_, bc) in enumerate(slots):
        bc["description"] = texts[(i - k) % n]
    return _retitle(doc, "swapped_v2", f"v2: real implementation texts rotated by {k} (second valid rotation); gap texts left in place.")


